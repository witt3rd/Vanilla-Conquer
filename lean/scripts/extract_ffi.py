def extract_unboxed_functions(ir_c_text: str) -> str:
    lines = ir_c_text.splitlines()
    out_lines = []
    skip_block = False
    brace_depth = 0

    for line in lines:
        # Stop before runtime initialization footer
        if line.startswith("lean_object* initialize_Init"):
            break

        # Skip header preamble up to first LEAN_EXPORT
        if not out_lines and not line.startswith("LEAN_EXPORT "):
            continue

        # Skip forward declarations of ___boxed
        if "___boxed(" in line and line.endswith(";"):
            continue

        # Detect start of a boxed wrapper (`___boxed`) and skip its body
        if line.startswith("LEAN_EXPORT lean_object* ") and "___boxed(" in line:
            skip_block = True
            brace_depth = line.count("{") - line.count("}")
            continue

        if skip_block:
            brace_depth += line.count("{") - line.count("}")
            if brace_depth <= 0:
                skip_block = False
            continue

        out_lines.append(line)

    out_lines.append("#ifdef __cplusplus")
    out_lines.append("}")
    out_lines.append("#endif")
    out_lines.append("")
    return "\n".join(out_lines)


def main() -> int:
    repo_root = pathlib.Path(__file__).resolve().parents[2]
    ir_c_path = repo_root / "lean" / ".lake" / "build" / "ir" / "CnCLean" / "FFI" / "Export.c"
    if not ir_c_path.exists():
        print(f"Error: {ir_c_path} does not exist. Run `lake -d lean build` first.", file=sys.stderr)
        return 1

    ir_c_text = ir_c_path.read_text(encoding="utf-8")
    unboxed_body = extract_unboxed_functions(ir_c_text)

    h_path = repo_root / "common" / "cnc_lean_ffi.h"
    c_path = repo_root / "common" / "cnc_lean_ffi.c"

    h_path.write_text(HEADER_CONTENT, encoding="utf-8")
    c_path.write_text(LEAN_SCALAR_PRIMITIVES + "\n" + unboxed_body, encoding="utf-8")
    print(f"Wrote {h_path} and {c_path} ({len(unboxed_body.splitlines())} lines of Lean-generated C).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
